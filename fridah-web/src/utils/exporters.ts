/**
 * Client-side document generation: PDF, Word (.docx), Excel (.xlsx) and CSV.
 * Libraries are loaded on demand so they never weigh down the first page load.
 * Everything is built from data already on screen — nothing leaves the browser.
 */
import { formatKES, formatDate } from './formatters'
import { useAuthStore } from '@/stores/auth'
import { company, companyLines, paymentLines, loadLogo } from '@/config/company'

export type ExportFormat = 'pdf' | 'docx' | 'xlsx' | 'csv'
export interface Col { key: string; label: string; format?: (v: any, row: any) => string }
export interface Meta { title: string; subtitle?: string; filename?: string }
export type SummaryItem = [label: string, value: string | number]

const MONEY = /(amount|balance|rent|paid|price|total|fee|revenue|commission|deposit|payout|collected|overdue)/i
const SKIP = /(^id$|_id$|^uuid$|pdf|receipt|document|image|photo|avatar|token|password|metadata|^url$)/i
const ISO_DATE = /^\d{4}-\d{2}-\d{2}(T|$)/

const humanize = (k: string) => k.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())
const today = () => new Date().toLocaleDateString('en-KE', { day: 'numeric', month: 'long', year: 'numeric' })
const stamp = () => new Date().toISOString().slice(0, 10)
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'report'

function preparedBy(): string {
  try { const u = useAuthStore().user; return u ? `${u.first_name} ${u.last_name}`.trim() : '' } catch { return '' }
}

/** Picks sensible columns from raw rows: readable fields only, money as KES, ISO dates formatted. */
export function autoColumns(rows: Record<string, any>[]): Col[] {
  if (!rows.length) return []
  return Object.keys(rows[0])
    .filter((k) => !SKIP.test(k) && ['string', 'number', 'boolean'].includes(typeof rows[0][k]))
    .filter((k) => typeof rows[0][k] !== 'string' || rows[0][k].length < 80)
    .slice(0, 9)
    .map((key) => ({
      key, label: humanize(key),
      format: (v: any) => {
        if (v === null || v === undefined || v === '') return '—'
        if (typeof v === 'number' && MONEY.test(key)) return formatKES(v)
        if (typeof v === 'string' && MONEY.test(key) && v !== '' && !isNaN(Number(v))) return formatKES(Number(v))
        if (typeof v === 'string' && ISO_DATE.test(v)) return formatDate(v)
        if (typeof v === 'boolean') return v ? 'Yes' : 'No'
        return String(v)
      },
    }))
}

function download(blob: Blob, filename: string) {
  const a = document.createElement('a')
  a.href = URL.createObjectURL(blob); a.download = filename
  document.body.appendChild(a); a.click(); a.remove()
  setTimeout(() => URL.revokeObjectURL(a.href), 2000)
}
const cell = (c: Col, r: any) => (c.format ? c.format(r[c.key], r) : r[c.key] == null ? '—' : String(r[c.key]))

/* ───────────── PDF ───────────── */
async function newPdf(meta: Meta) {
  const { jsPDF } = await import('jspdf')
  const autoTable = (await import('jspdf-autotable')).default
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const W = doc.internal.pageSize.getWidth()
  const logo = await loadLogo()
  if (logo) { try { doc.addImage(logo.data, logo.type, 40, 34, 38, 38) } catch { /* unreadable image: use the badge */ } }
  if (!logo) { doc.setFillColor(17, 24, 39); doc.roundedRect(40, 36, 34, 34, 8, 8, 'F'); doc.setTextColor(255); doc.setFont('helvetica', 'bold'); doc.setFontSize(18); doc.text(company.name.charAt(0).toUpperCase(), 52.5, 59) }
  doc.setTextColor(17, 24, 39); doc.setFont('helvetica', 'bold'); doc.setFontSize(15); doc.text(company.name, 88, 50)
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(110)
  const lines = [company.tagline, ...companyLines()].filter(Boolean)
  lines.slice(0, 4).forEach((l, n) => doc.text(l, 88, 62 + n * 10.5))
  doc.setFontSize(9); doc.text(today(), W - 40, 50, { align: 'right' })
  const by = preparedBy(); if (by) doc.text(`Prepared by ${by}`, W - 40, 62, { align: 'right' })
  const rule = 62 + Math.max(lines.slice(0, 4).length - 1, 1) * 10.5 + 14
  doc.setDrawColor(229, 231, 235); doc.line(40, rule, W - 40, rule)
  doc.setTextColor(17, 24, 39); doc.setFont('helvetica', 'bold'); doc.setFontSize(20); doc.text(meta.title, 40, rule + 32)
  if (meta.subtitle) { doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(110); doc.text(meta.subtitle, 40, rule + 49) }
  const footer = () => {
    const n = doc.getNumberOfPages()
    for (let i = 1; i <= n; i++) {
      doc.setPage(i); doc.setFontSize(8); doc.setTextColor(150)
      doc.text(company.invoiceFooter || `Generated by ${company.name}`, 40, doc.internal.pageSize.getHeight() - 24)
      doc.text(`Page ${i} of ${n}`, W - 40, doc.internal.pageSize.getHeight() - 24, { align: 'right' })
    }
  }
  return { doc, autoTable, W, footer, top: rule + (meta.subtitle ? 66 : 49) }
}

/* ───────────── Public API ───────────── */
export async function exportTable(format: ExportFormat, meta: Meta, rows: Record<string, any>[], columns?: Col[]) {
  const cols = columns?.length ? columns : autoColumns(rows)
  if (!rows.length || !cols.length) throw new Error('There is nothing to export yet.')
  const base = `${meta.filename || slug(meta.title)}-${stamp()}`
  const body = rows.map((r) => cols.map((c) => cell(c, r)))

  if (format === 'csv') {
    const esc = (v: string) => `"${v.replace(/"/g, '""')}"`
    const csv = [cols.map((c) => esc(c.label)).join(','), ...body.map((r) => r.map(esc).join(','))].join('\n')
    return download(new Blob(['\ufeff' + csv], { type: 'text/csv;charset=utf-8' }), `${base}.csv`)
  }
  if (format === 'xlsx') {
    const { default: writeExcelFile } = await import('write-excel-file/browser')
    const header = cols.map((c) => ({ value: c.label, fontWeight: 'bold' as const, backgroundColor: '#111827', color: '#ffffff' }))
    const data: any[][] = [header, ...body.map((r) => r.map((v) => ({ value: v })))]
    const blob = await writeExcelFile(data as any, { columns: cols.map(() => ({ width: 20 })), sheet: meta.title.slice(0, 30) } as any).toBlob()
    return download(blob, `${base}.xlsx`)
  }
  if (format === 'pdf') {
    const { doc, autoTable, footer, top } = await newPdf(meta)
    autoTable(doc, {
      startY: top, head: [cols.map((c) => c.label)], body,
      styles: { fontSize: 8.5, cellPadding: 6, textColor: [31, 41, 55] }, headStyles: { fillColor: [17, 24, 39], textColor: 255, fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [247, 248, 250] }, margin: { left: 40, right: 40, bottom: 44 },
    })
    footer(); return download(doc.output('blob'), `${base}.pdf`)
  }
  const d = await import('docx')
  const border = { style: d.BorderStyle.SINGLE, size: 4, color: 'E5E7EB' }
  const borders = { top: border, bottom: border, left: border, right: border }
  const mk = (text: string, head = false) => new d.TableCell({
    borders, margins: { top: 60, bottom: 60, left: 90, right: 90 }, shading: head ? { fill: '111827', type: d.ShadingType.CLEAR } : undefined,
    children: [new d.Paragraph({ children: [new d.TextRun({ text, bold: head, color: head ? 'FFFFFF' : '1F2937', size: 17 })] })],
  })
  const table = new d.Table({ width: { size: 100, type: d.WidthType.PERCENTAGE }, rows: [new d.TableRow({ tableHeader: true, children: cols.map((c) => mk(c.label, true)) }), ...body.map((r) => new d.TableRow({ children: r.map((v) => mk(v)) }))] })
  const doc = new d.Document({
    sections: [{
      properties: { page: { size: { orientation: cols.length > 6 ? d.PageOrientation.LANDSCAPE : d.PageOrientation.PORTRAIT } } },
      children: [
        new d.Paragraph({ children: [new d.TextRun({ text: company.name, bold: true, size: 30 })] }),
        ...companyLines().map((l) => new d.Paragraph({ children: [new d.TextRun({ text: l, color: '6B7280', size: 17 })] })),
        new d.Paragraph({ children: [new d.TextRun({ text: `${today()}${preparedBy() ? ' · Prepared by ' + preparedBy() : ''}`, color: '6B7280', size: 18 })], spacing: { after: 240 } }),
        new d.Paragraph({ heading: d.HeadingLevel.HEADING_1, children: [new d.TextRun({ text: meta.title, bold: true })] }),
        ...(meta.subtitle ? [new d.Paragraph({ children: [new d.TextRun({ text: meta.subtitle, color: '6B7280' })], spacing: { after: 200 } })] : []),
        table,
      ],
    }],
  })
  return download(await d.Packer.toBlob(doc), `${base}.docx`)
}

/** A one-page report of headline figures (dashboards). */
export async function exportSummary(format: ExportFormat, meta: Meta, items: SummaryItem[]) {
  if (!items.length) throw new Error('There is nothing to export yet.')
  const cols: Col[] = [{ key: 'metric', label: 'Metric' }, { key: 'value', label: 'Value' }]
  const rows = items.map(([metric, value]) => ({ metric, value: typeof value === 'number' ? value.toLocaleString() : value }))
  return exportTable(format, meta, rows, cols)
}

export interface InvoiceLike {
  invoice_number: string; tenant_name?: string; invoice_type?: string; amount: number | string; amount_paid?: number | string; balance?: number | string
  period_start?: string; period_end?: string; due_date?: string; status?: string; amenity_name?: string
}

export async function exportInvoice(format: Extract<ExportFormat, 'pdf' | 'docx'>, inv: InvoiceLike) {
  const amount = Number(inv.amount), paid = Number(inv.amount_paid ?? 0), balance = Number(inv.balance ?? amount - paid)
  const kind = (inv.invoice_type || 'rent').replace(/^\w/, (c) => c.toUpperCase())
  const desc = `${kind}${inv.amenity_name ? ' – ' + inv.amenity_name : ''}${inv.period_start ? ` (${formatDate(inv.period_start)}${inv.period_end ? ' to ' + formatDate(inv.period_end) : ''})` : ''}`
  const status = (inv.status || 'pending').replace(/_/g, ' ').toUpperCase()
  const base = `invoice-${slug(inv.invoice_number)}`

  if (format === 'pdf') {
    const { doc, autoTable, W, footer, top } = await newPdf({ title: `Invoice ${inv.invoice_number}`, subtitle: `Status: ${status}` })
    const t0 = top + 12
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(31, 41, 55)
    doc.setFont('helvetica', 'bold'); doc.text('Billed to', 40, t0); doc.text('Details', W / 2 + 20, t0)
    doc.setFont('helvetica', 'normal')
    doc.text(inv.tenant_name || '—', 40, t0 + 16)
    doc.text(`Invoice no: ${inv.invoice_number}`, W / 2 + 20, t0 + 16)
    doc.text(`Due date: ${inv.due_date ? formatDate(inv.due_date) : '—'}`, W / 2 + 20, t0 + 31)
    autoTable(doc, {
      startY: t0 + 55, head: [['Description', 'Amount']], body: [[desc, formatKES(amount)]],
      styles: { fontSize: 10, cellPadding: 9 }, headStyles: { fillColor: [17, 24, 39], textColor: 255 }, columnStyles: { 1: { halign: 'right' } }, didParseCell: (d: any) => { if (d.section === 'head' && d.column.index === 1) d.cell.styles.halign = 'right' }, margin: { left: 40, right: 40 },
    })
    const y = (doc as any).lastAutoTable.finalY + 18
    autoTable(doc, {
      startY: y, theme: 'plain', body: [['Invoice total', formatKES(amount)], ['Amount paid', formatKES(paid)], ['Balance due', formatKES(balance)]],
      styles: { fontSize: 11, cellPadding: 5 }, columnStyles: { 0: { halign: 'right', cellWidth: 360 }, 1: { halign: 'right', fontStyle: 'bold' } }, margin: { left: 40, right: 40 },
      didParseCell: (d: any) => { if (d.row.index === 2) d.cell.styles.fontSize = 13 },
    })
    const y2 = (doc as any).lastAutoTable.finalY + 30
    doc.setFontSize(9); doc.setTextColor(110)
    doc.text(balance > 0 ? `Pay securely by M-Pesa from your ${company.name} tenant portal (Invoices > Pay).` : 'Thank you. This invoice is fully paid.', 40, y2)
    if (balance > 0) paymentLines().forEach((l, n) => doc.text(l, 40, y2 + 14 + n * 12))
    footer(); return download(doc.output('blob'), `${base}.pdf`)
  }
  const d = await import('docx')
  const row = (a: string, b: string, bold = false) => new d.TableRow({ children: [
    new d.TableCell({ children: [new d.Paragraph({ children: [new d.TextRun({ text: a, bold })] })] }),
    new d.TableCell({ children: [new d.Paragraph({ alignment: d.AlignmentType.RIGHT, children: [new d.TextRun({ text: b, bold })] })] }),
  ] })
  const doc = new d.Document({ sections: [{ children: [
    new d.Paragraph({ children: [new d.TextRun({ text: company.name, bold: true, size: 30 })] }),
        ...companyLines().map((l) => new d.Paragraph({ children: [new d.TextRun({ text: l, color: '6B7280', size: 17 })] })),
    new d.Paragraph({ heading: d.HeadingLevel.HEADING_1, children: [new d.TextRun({ text: `Invoice ${inv.invoice_number}` })] }),
    new d.Paragraph({ children: [new d.TextRun({ text: `Status: ${status}   |   Issued ${today()}`, color: '6B7280' })], spacing: { after: 200 } }),
    new d.Paragraph({ children: [new d.TextRun({ text: 'Billed to: ', bold: true }), new d.TextRun(inv.tenant_name || '—')] }),
    new d.Paragraph({ children: [new d.TextRun({ text: 'Due date: ', bold: true }), new d.TextRun(inv.due_date ? formatDate(inv.due_date) : '—')], spacing: { after: 240 } }),
    new d.Table({ width: { size: 100, type: d.WidthType.PERCENTAGE }, rows: [row('Description', 'Amount', true), row(desc, formatKES(amount)), row('Amount paid', formatKES(paid)), row('Balance due', formatKES(balance), true)] }),
    new d.Paragraph({ children: [new d.TextRun({ text: balance > 0 ? `Pay securely by M-Pesa from your ${company.name} tenant portal.` : 'Thank you. This invoice is fully paid.', color: '6B7280', size: 18 })], spacing: { before: 300 } }),
    ...(balance > 0 ? paymentLines() : []).map((l) => new d.Paragraph({ children: [new d.TextRun({ text: l, color: '6B7280', size: 18 })] })),
  ] }] })
  return download(await d.Packer.toBlob(doc), `${base}.docx`)
}
